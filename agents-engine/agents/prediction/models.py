"""
Data Models and Schema Definitions for AEGIS Ω Prediction Engine.
"""

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class MetricReading(BaseModel):
    """An individual telemetry metric measurement."""
    asset_id: str
    metric_name: str
    value: float
    timestamp: float = Field(default_factory=lambda: datetime.now(timezone.utc).timestamp())


class TrendForecast(BaseModel):
    """Result of deterministic linear regression and time-to-breach projection."""
    asset_id: str
    metric_name: str
    current_value: float
    hard_threshold: float
    slope_per_sec: float
    projected_seconds_to_breach: float
    is_breach_imminent: bool
    data_points_count: int


class PredictedIncident(BaseModel):
    """
    Schema for an anticipated incident flagged before crossing hard thresholds:
    {
        incident_id, correlation_id, asset_id, metric_name, current_value,
        hard_threshold, projected_seconds_to_breach, status, root_cause_prediction,
        confidence, historical_pattern, recommended_strategy, predicted_at
    }
    """
    incident_id: str
    correlation_id: str
    asset_id: str
    metric_name: str
    current_value: float
    hard_threshold: float
    projected_seconds_to_breach: float
    status: str = "PREDICTED_INCIDENT"
    root_cause_prediction: str
    confidence: float = Field(default=0.88, ge=0.0, le=1.0)
    historical_pattern: Optional[str] = None
    recommended_strategy: Optional[str] = None
    predicted_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class PredictionInput(BaseModel):
    """Telemetry metric or system event input to Prediction Engine."""
    asset_id: str
    metric_name: str
    value: float
    correlation_id: Optional[str] = None
    timestamp: Optional[float] = None
    threshold: Optional[float] = None


class PredictionOutput(BaseModel):
    """Output payload generated by Prediction Engine for Planner remediation pipeline."""
    incident_id: str
    correlation_id: str
    root_asset_id: str
    root_cause: str
    primary_failure_cause: str
    affected_systems: List[str] = Field(default_factory=list)
    confidence_score: float = 0.88
    status: str = "PREDICTED_INCIDENT"
    forecast: Optional[TrendForecast] = None
    blast_radius: Dict[str, Any] = Field(default_factory=dict)
    predicted_incident: Optional[PredictedIncident] = None
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
